import { Router } from 'express'
import { z } from 'zod'
import { prisma } from '../lib/prisma.js'
import type { AuthRequest } from '../middleware/auth.js'
import { optionalAuth, requireAuth } from '../middleware/auth.js'
import { resumeAt, validateVtt, watchedFraction } from '../services/player.js'
import { param } from '../lib/params.js'
import { enrichVideo } from '../services/videos.js'
import { toPublicUser } from '../lib/user.js'

export const videosRouter = Router()

const progressSchema = z.object({
  position: z.number().finite().min(0),
  duration: z.number().finite().positive().max(60 * 60 * 24),
})

const captionSchema = z.object({
  language: z.string().regex(/^[a-z]{2,3}(-[A-Z]{2})?$/, 'Language must be a code like "en" or "pt-BR"'),
  label: z.string().trim().min(1).max(60),
  content: z.string().min(1).max(200_000),
})

const captionList = {
  select: { id: true, language: true, label: true, autoGenerated: true },
  orderBy: { label: 'asc' },
} as const

videosRouter.get('/', optionalAuth, async (req: AuthRequest, res) => {
  const q = String(req.query.q ?? '').toLowerCase()
  const category = String(req.query.category ?? '')
  const where: import('@prisma/client').Prisma.VideoWhereInput = { published: true }
  if (category) where.category = category
  if (q) {
    where.OR = [
      { title: { contains: q } },
      { description: { contains: q } },
    ]
  }
  const videos = await prisma.video.findMany({
    where,
    take: 40,
    orderBy: { viewCount: 'desc' },
    include: { author: true },
  })
  const progress = req.userId
    ? await prisma.watchProgress.findMany({
        where: { userId: req.userId, videoId: { in: videos.map((v) => v.id) } },
      })
    : []
  res.json(
    videos.map((v) => ({
      id: v.id,
      title: v.title,
      thumbnailUrl: v.thumbnailUrl,
      viewCount: v.viewCount,
      duration: v.duration,
      createdAt: v.createdAt,
      progress: watchedFraction(progress.find((p) => p.videoId === v.id)),
      channel: {
        id: v.author.id,
        username: v.author.username,
        channelName: v.author.channelName || v.author.firstName,
        avatarUrl: v.author.avatarUrl,
      },
    })),
  )
})

// Public so <track src> can load it (browsers send no Authorization header for text tracks).
videosRouter.get('/:id/captions/:captionId', async (req, res) => {
  const caption = await prisma.videoCaption.findFirst({
    where: { id: param(req, 'captionId'), videoId: param(req, 'id'), video: { published: true } },
  })
  if (!caption) return res.status(404).json({ message: 'Not found' })
  res.type('text/vtt; charset=utf-8').set('Cache-Control', 'public, max-age=300').send(caption.content)
})

videosRouter.get('/:id', requireAuth, async (req: AuthRequest, res) => {
  const id = param(req, 'id')
  const video = await enrichVideo(id, req.userId!)
  if (!video) return res.status(404).json({ message: 'Not found' })
  await prisma.video.update({ where: { id }, data: { viewCount: { increment: 1 } } })
  const comments = await prisma.videoComment.findMany({
    where: { videoId: id },
    include: { user: true },
    orderBy: { createdAt: 'desc' },
    take: 50,
  })
  const related = await prisma.video.findMany({
    where: { authorId: video.channel.id, id: { not: id }, published: true },
    take: 8,
    orderBy: { viewCount: 'desc' },
  })
  const relatedEnriched = []
  for (const r of related) {
    const e = await enrichVideo(r.id, req.userId!)
    if (e) relatedEnriched.push(e)
  }
  const [captions, progress, settings] = await Promise.all([
    prisma.videoCaption.findMany({ where: { videoId: id }, ...captionList }),
    prisma.watchProgress.findUnique({ where: { userId_videoId: { userId: req.userId!, videoId: id } } }),
    prisma.userSettings.findUnique({ where: { userId: req.userId! } }),
  ])
  res.json({
    video: { ...video, viewCount: video.viewCount + 1 },
    isOwner: video.channel.id === req.userId,
    captions,
    resumeAt: resumeAt(progress),
    player: {
      playbackSpeed: settings?.playbackSpeed ?? 1,
      captionsLanguage: settings?.captionsLanguage ?? '',
      theaterMode: settings?.theaterMode ?? false,
    },
    comments: comments.map((c) => ({
      id: c.id,
      content: c.content,
      createdAt: c.createdAt,
      user: toPublicUser(c.user),
    })),
    related: relatedEnriched,
  })
})

videosRouter.use(requireAuth)

videosRouter.post('/', async (req: AuthRequest, res) => {
  const { title, description, videoUrl, thumbnailUrl, category, duration } = req.body as {
    title: string
    description?: string
    videoUrl: string
    thumbnailUrl?: string
    category?: string
    duration?: number
  }
  if (!title || !videoUrl) return res.status(400).json({ message: 'title and videoUrl required' })
  const video = await prisma.video.create({
    data: {
      authorId: req.userId!,
      title,
      description: description ?? '',
      videoUrl,
      thumbnailUrl: thumbnailUrl ?? `https://picsum.photos/seed/yt${Date.now()}/640/360`,
      category: category ?? 'General',
      duration: duration ?? 0,
    },
  })
  res.status(201).json(await enrichVideo(video.id, req.userId!))
})

videosRouter.post('/:id/like', async (req: AuthRequest, res) => {
  const videoId = param(req, 'id')
  const userId = req.userId!
  const existing = await prisma.videoLike.findUnique({
    where: { videoId_userId: { videoId, userId } },
  })
  if (existing) await prisma.videoLike.delete({ where: { id: existing.id } })
  else await prisma.videoLike.create({ data: { videoId, userId } })
  res.json(await enrichVideo(videoId, userId))
})

videosRouter.post('/:id/comment', async (req: AuthRequest, res) => {
  const { content } = req.body as { content: string }
  const comment = await prisma.videoComment.create({
    data: { videoId: param(req, 'id'), userId: req.userId!, content },
    include: { user: true },
  })
  res.status(201).json({ ...comment, user: toPublicUser(comment.user) })
})

videosRouter.put('/:id/progress', async (req: AuthRequest, res) => {
  const parsed = progressSchema.safeParse(req.body)
  if (!parsed.success) return res.status(400).json({ message: parsed.error.issues[0]?.message ?? 'Invalid progress' })
  const videoId = param(req, 'id')
  if (!(await prisma.video.findUnique({ where: { id: videoId }, select: { id: true } }))) {
    return res.status(404).json({ message: 'Not found' })
  }
  const { duration } = parsed.data
  const position = Math.min(parsed.data.position, duration)
  await prisma.watchProgress.upsert({
    where: { userId_videoId: { userId: req.userId!, videoId } },
    create: { userId: req.userId!, videoId, position, duration },
    update: { position, duration },
  })
  res.status(204).end()
})

/** Subtitle management is creator-only. */
async function ownVideo(req: AuthRequest) {
  const video = await prisma.video.findUnique({ where: { id: param(req, 'id') }, select: { id: true, authorId: true } })
  if (!video) return { status: 404, message: 'Not found' } as const
  if (video.authorId !== req.userId) return { status: 403, message: 'Forbidden' } as const
  return { status: 200, video } as const
}

videosRouter.post('/:id/captions', async (req: AuthRequest, res) => {
  const owned = await ownVideo(req)
  if (owned.status !== 200) return res.status(owned.status).json({ message: owned.message })
  const parsed = captionSchema.safeParse(req.body)
  if (!parsed.success) return res.status(400).json({ message: parsed.error.issues[0]?.message ?? 'Invalid subtitles' })
  const { language, label, content } = parsed.data
  const vttError = validateVtt(content)
  if (vttError) return res.status(400).json({ message: vttError })
  // One track per language: re-uploading replaces it (and it stops being auto-generated).
  await prisma.videoCaption.upsert({
    where: { videoId_language: { videoId: owned.video.id, language } },
    create: { videoId: owned.video.id, language, label, content },
    update: { label, content, autoGenerated: false },
  })
  res.status(201).json(await prisma.videoCaption.findMany({ where: { videoId: owned.video.id }, ...captionList }))
})

videosRouter.delete('/:id/captions/:captionId', async (req: AuthRequest, res) => {
  const owned = await ownVideo(req)
  if (owned.status !== 200) return res.status(owned.status).json({ message: owned.message })
  const { count } = await prisma.videoCaption.deleteMany({
    where: { id: param(req, 'captionId'), videoId: owned.video.id },
  })
  if (!count) return res.status(404).json({ message: 'Not found' })
  res.status(204).end()
})
